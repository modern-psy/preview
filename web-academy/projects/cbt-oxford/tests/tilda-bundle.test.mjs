import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root = new URL('../tilda/', import.meta.url);
const hash = value => createHash('sha256').update(value).digest('hex');
test('Exact Tilda fragments form the public preview and fit the editor limit', async () => {
  const manifest = JSON.parse(await fs.readFile(new URL('manifest.json', root), 'utf8'));
  const formContract = JSON.parse(await fs.readFile(new URL('../data/form-contract.json', root), 'utf8'));
  const files = await Promise.all(manifest.files.map(async record => {
    const text = await fs.readFile(new URL(record.file, root), 'utf8');
    assert.equal(text.length, record.characters);
    assert.equal(hash(text), record.sha256);
    assert.ok(text.length < 65000);
    assert.doesNotMatch(text, /(?:src|href)="(?:assets\/|\.\.\/|http:\/\/localhost)|\.\.\/\.\.\/shared\//);
    return text;
  }));
  const preview = await fs.readFile(new URL('preview.html', root), 'utf8');
  const expected = `<!doctype html><html lang="ru"><head>${files.filter((_,i)=>['HEAD','STYLE'].includes(manifest.files[i].placement)).join('\n')}</head><body><main class="t-records">${files.filter((_,i)=>manifest.files[i].placement==='BODY').join('\n')}</main>${files.filter((_,i)=>manifest.files[i].placement==='FOOTER').join('\n')}</body></html>\n`;
  assert.equal(preview, expected);
  assert.equal(hash(preview), manifest.previewSha256);
  assert.equal((preview.match(/<h1\b/g) || []).length, 1);
  assert.equal((preview.match(/<academy-practice-stories\b/g) || []).length, 1);
  assert.equal((preview.match(/<blockquote\b/g) || []).length, 5);
  assert.equal((preview.match(/href="#cbt-oxford-form"/g) || []).length, 2);
  assert.equal((preview.match(/href="#cbt-oxford-program"/g) || []).length, 1);
  assert.equal((preview.match(/href="#form"[^>]*data-tilda-popup-link/g) || []).length, 1);
  assert.equal((preview.match(/href="#program"[^>]*data-tilda-popup-link/g) || []).length, 1);
  assert.equal((preview.match(/href="#free-oxford"/g) || []).length, 1);
  assert.equal((preview.match(/href="#free-oxford"[^>]*data-tilda-popup-link/g) || []).length, 1);
  assert.equal((preview.match(/<section\b[^>]*id="cbt-oxford-form"/g) || []).length, 1);
  assert.equal((preview.match(/<section\b[^>]*id="cbt-oxford-program"/g) || []).length, 1);
  assert.doesNotMatch(preview, /<section\b[^>]*id="(?:form|program)"/);
  assert.doesNotMatch(preview, /href="#application"/);
  assert.match(preview, /--anchor-scroll-offset:\s*50px/);
  assert.match(preview, /@media \(min-width: 48rem\)[^{]*\{[^}]*--anchor-scroll-offset:\s*100px/);
  assert.match(preview, /\.cbt-oxford-page\[data-cbt-part\]\s*\{\s*min-height:\s*0/);
  assert.match(preview, /\.cbt-oxford-page \.button_component\.is-accent\s*\{\s*color:\s*var\(--color-text-on-dark\)\s*!important/);
  assert.equal((preview.match(new RegExp(`data-tilda-form-name="${formContract.nativeMarker}"`, 'g')) || []).length, 1);
  assert.match(preview, /querySelectorAll\("form\.t-form"\)/);
  assert.match(preview, /input\[name="tildaspec-formname"\]/);
  assert.match(preview, /nativeForm\.closest\("\.t-rec"\) \|\| nativeForm/);
  assert.match(preview, /record\.hidden = true/);
  assert.match(preview, /record\.setAttribute\("aria-hidden", "true"\)/);
  assert.match(preview, /record\.setAttribute\("data-academy-native-form-record", ""\)/);
  assert.match(preview, /new MutationObserver\(hideKnownTildaForms\)/);
  const bodySections = manifest.files.filter(record => /^\d{2}-body-/.test(record.file));
  assert.equal(bodySections.length, 14);
  bodySections.forEach((record, index) => {
    assert.ok(record.file.startsWith(`${String(index + 1).padStart(2, '0')}-body-`));
    assert.match(files[manifest.files.indexOf(record)], new RegExp(`^<!-- Секция ${String(index + 1).padStart(2, '0')}: .+ -->\\n`));
  });
  assert.ok(manifest.files.filter(record => record.placement !== 'BODY').every(record => !/^\d{2}-/.test(record.file)));
});
