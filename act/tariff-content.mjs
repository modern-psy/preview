const modules = [
  'Контекстуально-поведенческое мышление терапевта',
  'Терапевтические отношения и позиция специалиста',
  'Практические навыки АСТ-терапевта',
  'Этика, границы и профессиональная ответственность',
  'АСТ в работе с запросами: сессия «за стеклом» и разбор'
];
export function tariffContent(startDate, title) {
  if (!['2026-10-26', '2027-02-01', '2027-05-17'].includes(startDate) || !['Полный', 'Расширенный'].includes(title)) return null;
  const count = title === 'Полный' ? 4 : 5;
  return {count, rows: modules.map((text, index) => ({text, included: index < count}))};
}
