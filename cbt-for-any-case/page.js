/* ============================================================================
   СКРИПТ СТРАНИЦЫ «ПОЧЕМУ КПТ ПОДХОДИТ ПОЧТИ ПОД ЛЮБОЙ ЗАПРОС»
   ============================================================================

   ЧТО ОН ДЕЛАЕТ
   Ровно одно: раскрывает карточки уровней КПТ по мере прокрутки страницы.
   Сначала раскрыт только первый уровень, остальные лежат под ним узкими
   пилюлями. Чем дальше вы прокрутили, тем больше уровней раскрыто.
   Раскрытое обратно не закрывается.

   Ещё он подсказывает стилям, насколько узкой должна быть каждая свёрнутая
   пилюля: чем дальше она от последней раскрытой карточки, тем уже. Для этого
   каждой пилюле проставляется «глубина» — переменная --depth со значением
   1, 2, 3… Ширину из неё считает CSS (page.css, раздел 5).

   ПОЧЕМУ СДЕЛАНО ЧЕРЕЗ КЛАСС
   По умолчанию в CSS все карточки раскрыты. Скрипт сам вешает на список
   класс is-scroll-reveal и только этим включает свёрнутый вид. Значит,
   если скрипт не загрузится или в браузере выключен JavaScript, посетитель
   увидит все пять уровней сразу — страница не сломается.

   ⚠️ ПОЧЕМУ НЕ IntersectionObserver, ХОТЯ ОН БЫЛ ПЕРВЫМ РЕШЕНИЕМ
   Наблюдатель следил за каждой карточкой отдельно: «показалась — раскрой».
   Но раскрывшаяся карточка становится выше и сдвигает все следующие вниз,
   поэтому блок буквально убегал: чтобы дойти до пятого уровня, приходилось
   прокручивать так далеко, что первые уровни уже уезжали под липкую шапку.
   Теперь всё считается от ВЕРХА списка — а он при раскрытии не двигается,
   потому что карточки растут вниз. Убегать стало нечему.

   🔴 ЭТО «ШЕСТЕРЁНКИ». Текст уровней меняется в index.html, а не здесь.
   ============================================================================ */

(function () {
  'use strict';

  /* --------------------------------------------------------------------
     НАСТРОЙКИ. Тут можно подкрутить поведение, ничего не сломав.
     -------------------------------------------------------------------- */

  // Линия срабатывания: доля высоты экрана сверху.
  // 0.7 — ниже середины: блок успевает показаться на экране, и только
  // потом начинает раскрываться.
  // ⚠️ Было 0.85 (почти у нижнего края) — раскрытие начиналось раньше,
  // чем блок попадал в поле зрения.
  var TRIGGER = 0.7;

  // Сколько пикселей прокрутки приходится на один уровень.
  // Больше число — стопка раскрывается медленнее. Было 80.
  // Слишком большое число тоже плохо: пока дойдёт до пятого уровня,
  // первые уедут за верх экрана. 130 — золотая середина.
  var STEP = 130;

  /* -------------------------------------------------------------------- */

  var list = document.querySelector('[data-levels]');
  if (!list) return;

  var items = Array.prototype.slice.call(list.children);
  if (!items.length) return;

  // Если человек в настройках системы попросил меньше анимаций — не трогаем
  // ничего: пусть все уровни просто будут открыты.
  var calm = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)');
  if (calm && calm.matches) return;

  // Включаем свёрнутый вид (до этого момента в CSS всё было раскрыто).
  list.classList.add('is-scroll-reveal');

  var opened = 0;   // сколько уровней уже раскрыто

  /* Раскрывает первые n карточек и пересчитывает «глубину» остальных.
     Глубина 1 — сразу под последней раскрытой, дальше 2, 3, 4:
     чем больше число, тем уже пилюля. */
  function show(n) {
    if (n <= opened) return;              // назад не отматываем
    opened = n;

    var depth = 0;
    items.forEach(function (item, i) {
      if (i < opened) {
        item.classList.add('is-open');
        depth = 0;                        // счёт глубины начинается заново
        item.style.removeProperty('--depth');
      } else {
        depth += 1;
        item.style.setProperty('--depth', depth);
      }
    });
  }

  /* Считает, сколько уровней должно быть раскрыто при текущей прокрутке.
     Верх списка берём заново на каждый пересчёт: он не сдвигается, когда
     карточки раскрываются, поэтому число получается устойчивым. */
  function update() {
    var listTop = list.getBoundingClientRect().top + window.pageYOffset;
    var triggerLine = window.pageYOffset + window.innerHeight * TRIGGER;
    var passed = triggerLine - listTop;   // насколько линия ушла ниже верха списка

    var need = 1 + Math.floor(passed / STEP);
    if (need < 1) need = 1;               // первый уровень открыт всегда
    if (need > items.length) need = items.length;

    show(need);
  }

  update();
  window.addEventListener('scroll', update, { passive: true });
  window.addEventListener('resize', update);
})();
